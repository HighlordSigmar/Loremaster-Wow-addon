"""Convert OctoQuestDatabase (source/*.json) into Lua files shaped like the
pfQuest database (pfDB.<db>.data / pfDB.<db>.enUS), so gen.lua can read it.

JSON arrays are one-based Lua sequences; numeric string keys become numbers.
Big tables are split over several files (Lua 5.0 limits constants per chunk).

usage: python3 -I octo2lua.py <OctoQuestDatabase dir> <out dir>
"""
import json, os, sys

src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)


def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return '"' + s + '"'


def lua_key(k):
    if isinstance(k, str) and k.lstrip("-").isdigit():
        return "[" + k + "]"
    return "[" + lua_str(str(k)) + "]"


def lua_num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    r = repr(v)
    return r[:-2] if r.endswith(".0") else r


def lua(v):
    if isinstance(v, dict):
        return "{" + ",".join(lua_key(k) + "=" + lua(x) for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, str):
        return lua_str(v)
    if v is None:
        raise ValueError("null not supported")
    return lua_num(v)


def write_table(path_prefix, target, table, chunk=1500):
    keys = list(table.keys())
    files = []
    for n in range(0, max(len(keys), 1), chunk):
        name = "%s_%d.lua" % (path_prefix, n // chunk)
        with open(os.path.join(out, name), "w", encoding="utf-8") as f:
            f.write("local t = %s\n" % target)
            for k in keys[n:n + chunk]:
                f.write("t%s=%s\n" % (lua_key(k), lua(table[k])))
        files.append(name)
    return files


files = []
loc = json.load(open(os.path.join(src, "source", "locales.json"), encoding="utf-8"))
for db in ("quests", "units", "objects", "items"):
    data = json.load(open(os.path.join(src, "source", db + ".json"), encoding="utf-8"))
    files += write_table(db + "_data", 'pfDB["%s"]["data"]' % db, data)
    files += write_table(db + "_enUS", 'pfDB["%s"]["enUS"]' % db, loc.get(db, {}))
zones = json.load(open(os.path.join(src, "source", "zones.json"), encoding="utf-8"))
files += write_table("zones_data", 'pfDB["zones"]["data"]', zones)
files += write_table("zones_enUS", 'pfDB["zones"]["enUS"]', loc["zones"])
files += write_table("professions_enUS", 'pfDB["professions"]["enUS"]', loc["professions"])

with open(os.path.join(out, "load.lua"), "w") as f:
    f.write("-- generated by octo2lua.py\n")
    f.write("pfDB = {}\n")
    for db in ("quests", "units", "objects", "items", "zones", "professions"):
        f.write('pfDB["%s"] = { data = {}, enUS = {} }\n' % db)
    f.write("local dir = OCTODB_DIR\n")
    for name in files:
        f.write('dofile(dir .. "%s")\n' % name)
print("wrote %d files to %s" % (len(files) + 1, out))
